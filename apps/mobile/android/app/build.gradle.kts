// MOBILE-REL-01: release signing reads android/key.properties when that file exists. The release workflow writes
// it from repository secrets and deletes it afterwards. Without the file, release builds use the debug key so a
// local `flutter build apk --release` still works. The file and the keystore must never be committed.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseKey = keystorePropertiesFile.exists()
if (hasReleaseKey) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

fun requiredKeystoreProperty(name: String): String =
    keystoreProperties.getProperty(name)?.takeIf { it.isNotEmpty() }
        ?: error("android/key.properties must set $name")

